#!/usr/bin/env bash
# Local check run before every push: the commands the pull_request and main CI jobs run,
# whatever paths a change touches. Needs uv and kramdown-rfc (gem install kramdown-rfc) on PATH.
# Not run here: dco (commit sign-off), the neutrality term scan (needs the NEUTRALITY_TERMS
# secret; the scanner's self-test runs) and spec.yml's idnits step (non-gating in CI).
set -euo pipefail
cd "$(dirname "$0")/.."
command -v kramdown-rfc >/dev/null || { echo "kramdown-rfc not on PATH: gem install kramdown-rfc" >&2; exit 1; }
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
export PYTHONDONTWRITEBYTECODE=1
py() { uv run --isolated --no-project --python 3.12 --with "jsonschema>=4" --with "pyyaml>=6" --with "pytest>=7" --with xml2rfc "$@"; }

# leak-lint.yml
py python .github/leak_lint.py .
# neutrality.yml and vectors.yml
py python .github/neutrality_scan.py --self-test
# vectors.yml
py python .github/check_vectors.py vectors/
py python -m pytest -p no:cacheprovider .github/test_check_vectors.py -q
# candidate-validate.yml
py python .github/check_vectors.py --candidate vectors
# registry.yml
py python .github/gen_registry.py --check
py python -m pytest -p no:cacheprovider .github/test_gen_registry.py -q
py python - <<'PY'
import hashlib, json, pathlib, jsonschema
schema = json.loads(pathlib.Path(".github/registry_schema.json").read_text())
data = json.loads(pathlib.Path("registry.json").read_text())
jsonschema.validate(data, schema)
body = {k: v for k, v in data.items() if k != "snapshot_sha256"}
canon = json.dumps(body, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
assert hashlib.sha256(canon.encode("ascii")).hexdigest() == data["snapshot_sha256"], "snapshot_sha256 mismatch"
print("registry.json: schema valid, snapshot_sha256 consistent")
PY
# registry-entries.yml
py python -m pytest -p no:cacheprovider .github/test_validate_registry_entries.py -q
py python .github/validate_registry_entries.py registry/entries
# python.yml (matrix 3.11 and 3.12)
for v in 3.11 3.12; do
  (cd lib && uv run --isolated --no-project --python "$v" --with ".[dev]" --with "ruff>=0.4,<0.16" python -m ruff check --no-cache .)
  (cd lib && uv run --isolated --no-project --python "$v" --with ".[dev]" --with pip python -m pytest -p no:cacheprovider -q)
done
# spec.yml: rebuild the draft and compare with the committed .xml and .txt
DRAFT=$(grep '^DRAFT[[:space:]]*=' spec/Makefile | sed 's/^DRAFT[[:space:]]*=[[:space:]]*//')
(cd spec && kramdown-rfc "$DRAFT.md" > "$work/.draft.v2.xml")
py xml2rfc --quiet --v2v3 "$work/.draft.v2.xml" -o "$work/$DRAFT.xml"
py xml2rfc --quiet --text --v3 "$work/$DRAFT.xml" -o "$work/$DRAFT.txt"
strip_xml() {
  grep -v 'generated by.*kramdown-rfc' | grep -v 'xml2rfc v2v3 conversion' |
    sed 's/<date year="[^"]*" month="[^"]*" day="[^"]*"\/>/<date\/>/g'
}
strip_txt() {
  sed \
    -e 's/^Expires: [0-9][0-9]* [A-Za-z][A-Za-z]* [0-9][0-9][0-9][0-9]/Expires: DATE_NORM/' \
    -e 's/expire on [0-9][0-9]* [A-Za-z][A-Za-z]* [0-9][0-9][0-9][0-9]/expire on DATE_NORM/' \
    -e 's/Expires [0-9][0-9]* [A-Za-z][A-Za-z]* [0-9][0-9][0-9][0-9]  *\[Page/Expires DATE_NORM [Page/' \
    -e '/^ *[0-9][0-9]* [A-Za-z][A-Za-z]* [0-9][0-9][0-9][0-9] *$/s/.*/DATE_NORM/' \
    -e '/DATE_NORM/s/  */ /g'
}
diff <(strip_xml < "spec/$DRAFT.xml") <(strip_xml < "$work/$DRAFT.xml") || { echo "STALE: spec/$DRAFT.xml"; exit 1; }
diff <(strip_txt < "spec/$DRAFT.txt") <(strip_txt < "$work/$DRAFT.txt") || { echo "STALE: spec/$DRAFT.txt"; exit 1; }
grep -q 'version="3"' "$work/$DRAFT.xml"
echo "check.sh: all checks passed"
